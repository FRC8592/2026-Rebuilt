package frc.utils.generator;

import com.typesafe.config.Config;
import com.typesafe.config.ConfigFactory;
import com.typesafe.config.ConfigParseOptions;
import com.typesafe.config.ConfigValue;

import frc.utils.stormconfig.ConfigSchema;
import frc.utils.stormconfig.ConfigSchema.CompoundShape;
import frc.utils.stormconfig.ConfigSchema.ListShape;
import frc.utils.stormconfig.ConfigSchema.MeasureShape;
import frc.utils.stormconfig.ConfigSchema.ObjectShape;
import frc.utils.stormconfig.ConfigSchema.Scalar;
import frc.utils.stormconfig.ConfigSchema.Shape;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import javax.lang.model.SourceVersion;

import static java.lang.System.exit;

/**
 * Build-time step: checks config.conf and every robot file it lists, then writes Constants.java
 * with one typed field per config value. Any config error fails the build, with file:line.
 */
public class ConfigGenerator {

    private final Set<String> imports = new TreeSet<>();
    private final List<String> errors = new ArrayList<>();
    private final StringBuilder body = new StringBuilder();
    private final Config base;
    private final Config unresolvedBase;

    private ConfigGenerator(Config base, Config unresolvedBase) {
        this.base = base;
        this.unresolvedBase = unresolvedBase;
    }

    public static void main(String[] args) {
        if (args.length != 2) {
            System.err.println("usage: program INPUTFILEDIR OUTPUTFILENAME");
            exit(1);
        }
        File deployDir = new File(args[0]);
        File output = new File(args[1]);
        String className = output.getName().replace(".java", "");

        try {
            Config unresolvedBase = parse(new File(deployDir, "config.conf"));
            Config base = unresolvedBase.resolve();
            ObjectShape schema = ConfigSchema.fromBase(base);
            List<String> problems = checkAllRobots(deployDir, unresolvedBase, schema);
            if (!problems.isEmpty()) {
                fail(problems);
            }

            ConfigGenerator generator = new ConfigGenerator(base, unresolvedBase);
            String program = generator.program(className, schema);
            if (!generator.errors.isEmpty()) {
                fail(generator.errors);
            }
            try (FileWriter writer = new FileWriter(output)) {
                writer.write(program);
            }
            System.out.println("Constants file generated successfully.");
        } catch (RuntimeException e) {
            fail(List.of(e.getMessage()));
        } catch (IOException e) {
            fail(List.of("error writing " + output + ": " + e.getMessage()));
        }
    }

    /** Merges and checks every combination the robot can load at runtime. */
    private static List<String> checkAllRobots(File deployDir, Config unresolvedBase, ObjectShape schema) {
        ConfigSchema.Meta meta = ConfigSchema.meta(unresolvedBase);

        List<List<String>> combinations = new ArrayList<>();
        for (String robotFile : meta.robots().values()) {
            combinations.add(List.of(robotFile));
        }
        List<String> sim = new ArrayList<>();
        if (meta.sim() != null) {
            sim.add(meta.sim());
        }
        if (meta.simExtra() != null) {
            sim.add(meta.simExtra());
        }
        combinations.add(sim);

        List<String> problems = new ArrayList<>();
        for (List<String> files : combinations) {
            List<Config> overrides = new ArrayList<>();
            for (String file : files) {
                overrides.add(parse(new File(deployDir, file)));
            }
            String label = files.isEmpty() ? "config.conf" : "config.conf + " + String.join(" + ", files);
            for (String error : ConfigSchema.check(schema, ConfigSchema.merge(unresolvedBase, overrides))) {
                problems.add("[" + label + "] " + error);
            }
        }
        return problems;
    }

    // ---------------------------------------------------------------- code generation

    private String program(String className, ObjectShape schema) {
        imports.add("frc.utils.stormconfig.StormConfig");
        body.append("public final class ").append(className).append(" {\n");
        body.append("\tprivate static final StormConfig.Node C = StormConfig.root();\n\n");
        body.append("\tprivate ").append(className).append("() {}\n");
        writeMembers(schema, "", 1, List.of(className));
        body.append("}\n");

        StringBuilder program = new StringBuilder();
        program.append("/* This file was autogenerated from src/main/deploy/*.conf - do not edit it - any edits will be overwritten! */\n");
        program.append("package frc.robot;\n\n");
        for (String imp : imports) {
            program.append("import ").append(imp).append(";\n");
        }
        program.append("\n").append(body);
        return program.toString();
    }

    private void writeMembers(ObjectShape shape, String path, int depth, List<String> enclosing) {
        for (Map.Entry<String, Shape> entry : shape.fields().entrySet()) {
            String key = entry.getKey();
            String fullPath = path.isEmpty() ? key : path + "." + key;
            if (!checkIdentifier(key, fullPath)) {
                continue;
            }
            Shape field = entry.getValue();
            String tabs = "\t".repeat(depth);
            body.append("\n");

            if (field instanceof ObjectShape obj) {
                String nested = className(key, fullPath, enclosing);
                writeDoc(fullPath, tabs, false);
                body.append(tabs).append("public static final class ").append(nested).append(" {\n");
                writeMembers(obj, fullPath, depth + 1, append(enclosing, nested));
                body.append(tabs).append("}\n");
            } else if (field instanceof ListShape list && list.element() instanceof ObjectShape element) {
                String record = className(singular(key), fullPath, enclosing);
                writeRecord(record, element, fullPath, tabs, append(enclosing, record));
                writeDoc(fullPath, tabs, true);
                body.append(tabs).append("public static final List<").append(record).append("> ").append(key)
                        .append(" = C.getList(\"").append(fullPath).append("\", n1 -> ")
                        .append(construct(record, element, "n1", 1)).append(");\n");
            } else {
                writeDoc(fullPath, tabs, true);
                body.append(tabs).append("public static final ").append(javaType(field, false)).append(" ")
                        .append(key).append(" = C.get(\"").append(fullPath).append("\");\n");
            }
        }
    }

    /** One record per list-of-objects; nested plain objects become nested records. */
    private void writeRecord(String name, ObjectShape shape, String path, String tabs, List<String> enclosing) {
        List<String> components = new ArrayList<>();
        List<Runnable> nested = new ArrayList<>();
        for (Map.Entry<String, Shape> entry : shape.fields().entrySet()) {
            String key = entry.getKey();
            if (!checkIdentifier(key, path + "[]." + key)) {
                continue;
            }
            Shape field = entry.getValue();
            if (field instanceof ObjectShape obj) {
                String nestedName = className(key, path + "[]." + key, enclosing);
                components.add(nestedName + " " + key);
                nested.add(() -> writeRecord(nestedName, obj, path + "[]." + key, tabs + "\t", append(enclosing, nestedName)));
            } else if (field instanceof ListShape list && list.element() instanceof ObjectShape obj) {
                String nestedName = className(singular(key), path + "[]." + key, enclosing);
                components.add("List<" + nestedName + "> " + key);
                nested.add(() -> writeRecord(nestedName, obj, path + "[]." + key, tabs + "\t", append(enclosing, nestedName)));
            } else {
                components.add(javaType(field, false) + " " + key);
            }
        }
        body.append(tabs).append("public record ").append(name).append("(").append(String.join(", ", components)).append(") {");
        if (nested.isEmpty()) {
            body.append("}\n");
        } else {
            body.append("\n");
            nested.forEach(Runnable::run);
            body.append(tabs).append("}\n");
        }
    }

    /** {@code new Camera(n1.get("name"), n1.get("offset"))}, recursing into nested records and lists. */
    private String construct(String record, ObjectShape shape, String node, int depth) {
        List<String> args = new ArrayList<>();
        for (Map.Entry<String, Shape> entry : shape.fields().entrySet()) {
            String key = entry.getKey();
            Shape field = entry.getValue();
            if (field instanceof ObjectShape obj) {
                args.add(construct(record + "." + capitalize(key), obj, node + ".node(\"" + key + "\")", depth));
            } else if (field instanceof ListShape list && list.element() instanceof ObjectShape obj) {
                String inner = "n" + (depth + 1);
                args.add(node + ".getList(\"" + key + "\", " + inner + " -> "
                        + construct(record + "." + capitalize(singular(key)), obj, inner, depth + 1) + ")");
            } else {
                args.add(node + ".get(\"" + key + "\")");
            }
        }
        return "new " + record + "(" + String.join(", ", args) + ")";
    }

    private String javaType(Shape shape, boolean boxed) {
        if (shape instanceof Scalar s) {
            switch (s.kind()) {
                case BOOLEAN:
                    return boxed ? "Boolean" : "boolean";
                case INT:
                    return boxed ? "Integer" : "int";
                case LONG:
                    return boxed ? "Long" : "long";
                case DOUBLE:
                    return boxed ? "Double" : "double";
                default:
                    return "String";
            }
        }
        if (shape instanceof MeasureShape m) {
            imports.addAll(m.type().imports());
            return m.type().javaType();
        }
        if (shape instanceof CompoundShape c) {
            imports.add(c.type().importName());
            return c.type().name();
        }
        if (shape instanceof ListShape l) {
            imports.add("java.util.List");
            return "List<" + javaType(l.element(), true) + ">";
        }
        throw new IllegalStateException("unexpected shape " + shape);
    }

    /** Javadoc from the comments above the key in config.conf, plus where the default lives. */
    private void writeDoc(String path, String tabs, boolean withValue) {
        ConfigValue value = base.getValue(path);
        // Comments and line numbers come from the unresolved file: a resolved ${substitution}
        // reports the origin of the value it points at instead.
        ConfigValue source = unresolvedBase.root();
        for (String key : com.typesafe.config.ConfigUtil.splitPath(path)) {
            source = ((com.typesafe.config.ConfigObject) source).get(key);
        }
        List<String> lines = new ArrayList<>();
        for (String comment : source.origin().comments()) {
            String text = comment.trim();
            if (!text.isEmpty() && !text.matches("#+")) {
                lines.add(text.replace("*/", "* /"));
            }
        }
        if (withValue) {
            String rendered = value.render(com.typesafe.config.ConfigRenderOptions.concise());
            if (rendered.length() > 100) {
                rendered = rendered.substring(0, 97) + "...";
            }
            lines.add("config.conf:" + source.origin().lineNumber() + " = " + rendered.replace("*/", "* /"));
        }
        if (lines.isEmpty()) {
            return;
        }
        body.append(tabs).append("/**\n");
        for (String line : lines) {
            body.append(tabs).append(" * ").append(line).append("\n");
        }
        body.append(tabs).append(" */\n");
    }

    private boolean checkIdentifier(String key, String path) {
        if (!SourceVersion.isName(key) || key.contains(".")) {
            errors.add("config.conf: key '" + path + "' can't be a Java name (use letters, digits and _ only, not a Java keyword)");
            return false;
        }
        return true;
    }

    private String className(String key, String path, List<String> enclosing) {
        String name = capitalize(key);
        if (enclosing.contains(name)) {
            errors.add("config.conf: '" + path + "' would generate class " + name
                    + " inside a class of the same name, which Java doesn't allow; rename the key");
        }
        return name;
    }

    private static String capitalize(String key) {
        return key.substring(0, 1).toUpperCase() + key.substring(1);
    }

    /** CAMERAS -> CAMERA, modules -> module; otherwise add "Item". */
    private static String singular(String key) {
        if (key.length() > 1 && (key.endsWith("s") || key.endsWith("S"))) {
            return key.substring(0, key.length() - 1);
        }
        return key + "Item";
    }

    private static List<String> append(List<String> list, String item) {
        List<String> result = new ArrayList<>(list);
        result.add(item);
        return result;
    }

    private static Config parse(File file) {
        return ConfigFactory.parseFile(file, ConfigParseOptions.defaults().setAllowMissing(false));
    }

    private static void fail(List<String> problems) {
        System.err.println("Build Failed: config errors in src/main/deploy:");
        for (String problem : problems) {
            System.err.println("  " + problem);
        }
        exit(1);
    }
}
